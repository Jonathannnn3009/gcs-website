// Writes every loan's second-form questions (the ones the website asks after the short form) to a TypeScript file
// the CRM's WhatsApp assistant reads, so on WhatsApp it asks the same questions in the same order and the answers land
// in the CRM exactly as the website's would. Run:
//   npx tsx scripts/export-whatsapp-intake.ts "<path to gcs-crm>/backend/src/whatsapp/intake/intake-guide.ts"
import { writeFileSync } from "node:fs";
import { PRODUCTS } from "../src/data/products";
import { followUpFor } from "../src/data/follow-up-forms";
import { LOAN_KINDS } from "../src/data/loan-kinds";

type Field = { key: string; label: string; kind: string; options?: string[]; showWhen?: { key: string; values: string[] }; required?: boolean; help?: string; allowZero?: boolean };

const loans: Record<string, { title: string; group: string; kinds: string[]; kindSeeds: Record<string, Record<string, string>>; fields: Field[] }> = {};
let fieldCount = 0;

for (const p of PRODUCTS) {
  const form = followUpFor(p.slug);
  if (!form) continue;
  const fields: Field[] = [];
  for (const step of form.steps) {
    for (const f of step.fields as unknown as Record<string, unknown>[]) {
      const field: Field = { key: String(f.key), label: String(f.label), kind: String(f.kind) };
      if (Array.isArray(f.options)) field.options = f.options as string[];
      if (f.showWhen) field.showWhen = f.showWhen as Field["showWhen"];
      if (f.required) field.required = true;
      if (f.allowZero) field.allowZero = true;
      if (typeof f.help === "string") field.help = f.help;
      fields.push(field);
    }
  }
  fieldCount += fields.length;
  const kinds = LOAN_KINDS[p.slug] ?? [];
  const kindSeeds: Record<string, Record<string, string>> = {};
  for (const k of kinds) {
    const seeds = form.kindSeeds?.(k);
    if (seeds && Object.keys(seeds).length) kindSeeds[k] = seeds;
  }
  loans[p.slug] = { title: p.title, group: p.group, kinds, kindSeeds, fields };
}

const out = process.argv[2];
if (!out) throw new Error("Give the output path as the first argument.");
writeFileSync(
  out,
  `// GENERATED by the website's scripts/export-whatsapp-intake.ts. Do not edit by hand: re-run the script after the\n// website's second forms change.\n\nexport type IntakeField = {\n  key: string;\n  label: string;\n  kind: string;\n  options?: string[];\n  showWhen?: { key: string; values: string[] };\n  required?: boolean;\n  help?: string;\n  allowZero?: boolean;\n};\nexport type IntakeLoan = {\n  title: string;\n  group: string;\n  kinds: string[];\n  /** What a chosen kind of loan already answers. */\n  kindSeeds: Record<string, Record<string, string>>;\n  fields: IntakeField[];\n};\n\nexport const INTAKE_GUIDE: Record<string, IntakeLoan> = ${JSON.stringify(loans, null, 1)};\n`,
);
console.log(`loans: ${Object.keys(loans).length}, questions: ${fieldCount}`);
